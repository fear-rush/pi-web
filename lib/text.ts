/** The English text for a key, with `{name}` placeholders replaced. */
export function t(key: string, params: Record<string, string | number | undefined> = {}): string {
  const message = MESSAGES[key] ?? key;
  return message.replace(/\{([\w.-]+)\}/g, (token, name: string) => {
    const value = params[name];
    return value === undefined ? token : String(value);
  });
}

const RELATIVE_UNITS: [Intl.RelativeTimeFormatUnit, number][] = [
  ["second", 1_000],
  ["minute", 60_000],
  ["hour", 3_600_000],
  ["day", 86_400_000],
];

/** "3 minutes ago". The locale parameter is accepted and ignored; there is one language. */
export function formatRelativeTime(date: Date | string, _locale = "en-US", now = new Date()): string {
  const target = date instanceof Date ? date : new Date(date);
  const diffMs = target.getTime() - now.getTime();
  if (Number.isNaN(diffMs)) return "";
  const absMs = Math.abs(diffMs);
  const [unit, divisor] = RELATIVE_UNITS.find((_, index) => index === RELATIVE_UNITS.length - 1 || absMs < RELATIVE_UNITS[index + 1][1]) ?? RELATIVE_UNITS[0];
  return new Intl.RelativeTimeFormat("en-US", { numeric: "always" }).format(Math.round(diffMs / divisor), unit);
}

/** Today shows the time, earlier days a relative one. */
export function formatUpdatedTime(timestamp: number, _locale = "en-US", now = new Date()): string {
  const target = new Date(timestamp);
  if (Number.isNaN(target.getTime())) return "";
  const sameDay = target.getFullYear() === now.getFullYear()
    && target.getMonth() === now.getMonth()
    && target.getDate() === now.getDate();
  if (sameDay) return target.toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit" });
  return formatRelativeTime(target, "en-US", now);
}

/** The compact sidebar column: "now", "5m", "3h", "2d". */
export function formatShortRelativeTime(date: Date | string, _locale = "en-US", now = new Date()): string {
  const target = date instanceof Date ? date : new Date(date);
  const elapsedMs = now.getTime() - target.getTime();
  if (Number.isNaN(elapsedMs)) return "";
  const minutes = Math.floor(Math.max(0, elapsedMs) / 60_000);
  if (minutes < 1) return "now";
  if (minutes < 60) return `${minutes}m`;
  const hours = Math.floor(elapsedMs / 3_600_000);
  if (hours < 24) return `${hours}h`;
  const days = Math.floor(elapsedMs / 86_400_000);
  if (days < 7) return `${days}d`;
  if (days < 30) return `${Math.floor(days / 7)}w`;
  if (days < 365) return `${Math.max(1, Math.floor(days / 30))}mo`;
  return `${Math.floor(days / 365)}y`;
}
